# Let's parse both
def parse_name_line(line):
    # e.g.: 1 ABDILLAH PUTRA YAMA 6672 L 3150148820 JAKARTA
    # e.g.: 41 AHMAD RAFISQY AMMAR RAYYAN L 3194216015 TANGERANG
    # e.g.: 115 ANDITA FAUZIYAH ALAMSYAH P 3166754627 TANGERANG
    line = line.strip()
    if not line:
        return None
    m = re.match(r"^(\d+)\s+(.+)$", line)
    if not m:
        return None
    no = int(m.group(1))
    rest = m.group(2).strip()

    # Find gender L or P followed by NISN (10 digits) and tempat lahir
    # Pattern: ... (nipd)? (L|P) (\d{10}) (.*)
    m2 = re.search(r"^(.*?)(?:\s+(\d{4,5}))?\s+([LP])\s+(\d{10})\s+(.+)$", rest)
    if m2:
        nama = m2.group(1).strip()
        nipd = m2.group(2) or ''
        jk = m2.group(3).strip()
        nisn = m2.group(4).strip()
        tempat_lahir = m2.group(5).strip()
        return {
            'no': no,
            'nama': nama,
            'nipd': nipd,
            'jk': jk,
            'nisn': nisn,
            'tempatLahir': tempat_lahir
        }
    
    # Fallback if nipd is missing or formatted slightly differently
    m3 = re.search(r"^(.*?)\s+([LP])\s+(\d{10})\s+(.+)$", rest)
    if m3:
        nama = m3.group(1).strip()
        jk = m3.group(2).strip()
        nisn = m3.group(3).strip()
        tempat_lahir = m3.group(4).strip()
        return {
            'no': no,
            'nama': nama,
            'nipd': '',
            'jk': jk,
            'nisn': nisn,
            'tempatLahir': tempat_lahir
        }
    return None

def parse_rombel_line(line):
    line = line.strip()
    if not line:
        return None
    parts = line.split()
    rombel = parts[0] if len(parts) > 0 else 'Kelas 1'
    # Format to "Kelas 1A", "Kelas 5B", etc.
    if re.match(r"^[1-6][A-D]$", rombel):
        rombel = f"Kelas {rombel}"
    return rombel

